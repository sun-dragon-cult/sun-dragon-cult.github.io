/**
 * Copies the RQG system's generated JSON Schemas into src/data/rqg-schemas, which the
 * <SchemaTable> component renders.
 *
 *   pnpm sync:schemas v6.2.0                  a release tag (or any branch/commit) on GitHub
 *   pnpm sync:schemas ../fvtt-system-rqg      a local checkout of the system repo
 */
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/data/rqg-schemas");
const SCHEMA_DIR = "src/data-model/json-schemas/generated";
const RAW = "https://raw.githubusercontent.com/sun-dragon-cult/fvtt-system-rqg";

const source = process.argv[2];
if (!source) {
  console.error("Usage: pnpm sync:schemas <tag-or-branch | path to the system repo>");
  process.exit(1);
}

const localDir = path.resolve(source);
const isLocal = fs.existsSync(path.join(localDir, SCHEMA_DIR, "manifest.json"));

async function read(file) {
  if (isLocal) {
    return fs.readFileSync(path.join(localDir, SCHEMA_DIR, file), "utf8");
  }
  const response = await fetch(`${RAW}/${source}/${SCHEMA_DIR}/${file}`);
  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText}: ${source}/${file}`);
  }
  return response.text();
}

function localLabel() {
  const git = (...args) =>
    execFileSync("git", ["-C", localDir, ...args], { encoding: "utf8" }).trim();
  return `${git("rev-parse", "--abbrev-ref", "HEAD")} (${git("rev-parse", "--short", "HEAD")})`;
}

const manifest = JSON.parse(await read("manifest.json"));
fs.rmSync(OUT, { recursive: true, force: true });

const imports = [];
const entries = [];
for (const { file, documentType, type } of manifest.schemas) {
  const target = path.join(OUT, file);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, await read(file));
  const name = `${documentType.toLowerCase()}${type[0].toUpperCase()}${type.slice(1)}`;
  imports.push(`import ${name} from "./${file}";`);
  entries.push(`  "${file.replace(".schema.json", "")}": ${name} as SchemaNode,`);
}

const ref = isLocal ? localLabel() : source;
fs.writeFileSync(
  path.join(OUT, "index.ts"),
  `// Generated by scripts/sync-schemas.mjs - do not edit by hand.
import type { SchemaNode } from "@site/src/components/SchemaTable/schema-rows";
${imports.join("\n")}

export const schemaRef = ${JSON.stringify(ref)};

export const schemas: Record<string, SchemaNode> = {
${entries.join("\n")}
};
`,
);
console.log(
  `Synced ${manifest.schemas.length} schemas from ${ref} to ${path.relative(process.cwd(), OUT)}`,
);
